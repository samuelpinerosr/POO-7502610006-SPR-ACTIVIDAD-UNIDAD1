        System.out.println("   Una clase es una plantilla, molde o plano arquitectónico abstracto que define");
        System.out.println("   las propiedades (atributos) y comportamientos (métodos) que compartirán los");
        System.out.println("   elementos de un mismo tipo. Por sí sola no ocupa memoria para datos reales,");
